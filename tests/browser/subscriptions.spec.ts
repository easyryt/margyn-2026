test("users browse AI offers and complete verified Razorpay test checkout without seeing internal usage", async ({ page, context }) => {
  test.setTimeout(180000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await login(context, "9876543204");
  const plan = { id: "public-studio", name: "Pro AI", tokenLimit: 12000, imageLimit: 25, storageLimitBytes: 1024 ** 3, durationDays: 30, pricePaise: 24900, offers: ["AI product image generation", "AI listing assistance", "Priority support"], published: true };
  const saved = await context.request.put("/api/admin/subscription-settings", { headers: { Origin: origin }, data: { defaultTokenLimit: 0, plans: [plan, { ...plan, id: "hidden-studio", name: "Hidden AI", published: false }, { id: "legacy-basic", name: "Basic AI", tokenLimit: 1000, durationDays: 30 }] } });
  expect(saved.ok()).toBe(true);
  await context.request.post("/api/auth/logout", { headers: { Origin: origin } });
  await login(context, "9876543279");
  await page.route("https://checkout.razorpay.com/v1/checkout.js", route => route.fulfill({ contentType: "application/javascript", body: `
    window.Razorpay = function(options) {
      this.open = async function() {
        const paymentId = options.order_id.replace(/^order_/, "pay_");
        const key = await crypto.subtle.importKey("raw", new TextEncoder().encode("isolated-test-razorpay-secret"), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
        const bytes = await crypto.subtle.sign("HMAC", key, new TextEncoder().encode(options.order_id + "|" + paymentId));
        const signature = Array.from(new Uint8Array(bytes), value => value.toString(16).padStart(2, "0")).join("");
        options.handler({ razorpay_payment_id: paymentId, razorpay_order_id: options.order_id, razorpay_signature: signature });
      };
    };
  ` }));
  await page.goto("/tools/subscription");
  await expect(page.getByRole("heading", { name: "Choose your AI plan", exact: true })).toBeVisible();
  const card = page.getByRole("article", { name: "Pro AI plan", exact: true });
  await expect(card).toContainText("₹249");
  await expect(card).toContainText("AI product image generation");
  await expect(card).toContainText("Priority support");
  await expect(page.getByRole("article", { name: "Hidden AI plan", exact: true })).toHaveCount(0);
  await expect(page.getByRole("article", { name: "Basic AI plan", exact: true })).toContainText("Pricing coming soon");
  await expect(page.locator("body")).not.toContainText(/tokens?/i);
  const catalog = await (await context.request.get("/api/subscription/plans")).json();
  expect(JSON.stringify(catalog)).not.toMatch(/token/i);
  await card.getByRole("button", { name: "Buy plan", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Pro AI is active");
  await expect(page.locator(".ai-current-plan").getByRole("heading", { name: "Pro AI", exact: true })).toBeVisible();
  await expect(card.getByRole("button", { name: "Current plan", exact: true })).toBeDisabled();
  await expect(page.getByRole("link", { name: "AI available", exact: true })).toBeVisible();
  const subscription = await (await context.request.get("/api/subscription")).json();
  expect(subscription.subscription.canUseAi).toBe(true);
  expect(subscription.subscription.offers).toEqual(plan.offers);
  expect(JSON.stringify(subscription)).not.toMatch(/token/i);
  await expect(page.locator("body")).not.toContainText(/tokens?/i);
  fs.mkdirSync(".test-data/screenshots", { recursive: true });
  await page.screenshot({ path: ".test-data/screenshots/ai-plans-desktop.png", fullPage: true });
  await page.reload();
  await expect(page.locator(".ai-current-plan")).toContainText("Pro AI");
  await expect(page.getByText("Plan activated", { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: ".test-data/screenshots/ai-plans-mobile.png", fullPage: true });
  expect(errors).toEqual([]);
});
