import { test, expect, type BrowserContext } from "@playwright/test";
import fs from "node:fs";
const origin = "http://127.0.0.1:3100";
async function login(context: BrowserContext, phone: string) {
  const sent = await context.request.post(origin + "/api/auth/request-otp", { headers: { Origin: origin }, data: { phone } });
  const challenge = await sent.json();
  const verified = await context.request.post(origin + "/api/auth/verify-otp", { headers: { Origin: origin }, data: { challengeId: challenge.challengeId, code: challenge.developmentCode } });
  expect(verified.ok()).toBeTruthy();
}
